import { z } from "zod";

/*
 * Per-tenant "Playbook de ventas": ethical sales guidance injected into the AI turn.
 * The playbook only shapes tone and order of the conversation. It never relaxes the hard
 * rules: every price / stock / lead-time claim still cites `knowledge_chunks` or hands off.
 */

export const SALES_STAGES = ["discovery", "proposal", "objections", "closing", "followup"] as const;
export const salesStageSchema = z.enum(SALES_STAGES);
export type SalesStage = z.infer<typeof salesStageSchema>;

export const CLOSING_STYLES = ["soft", "direct"] as const;
export const closingStyleSchema = z.enum(CLOSING_STYLES);
export type ClosingStyle = z.infer<typeof closingStyleSchema>;

export const PLAYBOOK_MAX_OBJECTIONS = 20;
export const PLAYBOOK_STAGE_MAX_CHARS = 500;
export const PLAYBOOK_OBJECTION_TRIGGER_MAX_CHARS = 200;
export const PLAYBOOK_OBJECTION_RESPONSE_MAX_CHARS = 600;
/** Follow-ups go out as free text, so they must land inside the WhatsApp 24 h window. */
export const PLAYBOOK_FOLLOW_UP_MAX_DELAY_HOURS = 23;
export const PLAYBOOK_FOLLOW_UP_MAX_COUNT = 5;

export const playbookObjectionSchema = z.object({
  /** Stable key the model returns in `objection`; generated by the editor. */
  id: z.string().trim().regex(/^[a-z0-9_-]{1,40}$/),
  /** Plain description of what the customer says or means (used for matching and shown to the model). */
  trigger: z.string().trim().min(1).max(PLAYBOOK_OBJECTION_TRIGGER_MAX_CHARS),
  /** Approved guidance for the answer. */
  response: z.string().trim().min(1).max(PLAYBOOK_OBJECTION_RESPONSE_MAX_CHARS),
});
export type PlaybookObjection = z.infer<typeof playbookObjectionSchema>;

const stageGuidanceSchema = z.string().trim().max(PLAYBOOK_STAGE_MAX_CHARS);

export const playbookFollowUpSchema = z.object({
  enabled: z.boolean(),
  delayHours: z.number().int().min(1).max(PLAYBOOK_FOLLOW_UP_MAX_DELAY_HOURS),
  maxFollowUps: z.number().int().min(1).max(PLAYBOOK_FOLLOW_UP_MAX_COUNT),
});
export type PlaybookFollowUp = z.infer<typeof playbookFollowUpSchema>;

export const playbookConfigSchema = z.object({
  enabled: z.boolean(),
  stages: z.object({
    discovery: stageGuidanceSchema,
    proposal: stageGuidanceSchema,
    objections: stageGuidanceSchema,
    closing: stageGuidanceSchema,
    followup: stageGuidanceSchema,
  }),
  objections: z
    .array(playbookObjectionSchema)
    .max(PLAYBOOK_MAX_OBJECTIONS)
    .refine((list) => new Set(list.map((o) => o.id)).size === list.length, { message: "objection ids must be unique" }),
  closingStyle: closingStyleSchema,
  followUp: playbookFollowUpSchema,
});
export type PlaybookConfig = z.infer<typeof playbookConfigSchema>;

/** `GET /ai/playbook` and `PUT /ai/playbook` share the same shape. */
export const playbookResponseSchema = playbookConfigSchema.extend({
  /** False while the tenant never saved a playbook (defaults are shown, disabled). */
  saved: z.boolean(),
  updatedAt: z.string().nullable(),
});
export type PlaybookResponse = z.infer<typeof playbookResponseSchema>;

export const savePlaybookRequestSchema = playbookConfigSchema;
export type SavePlaybookRequest = z.infer<typeof savePlaybookRequestSchema>;

/** What the worker hands to the prompt builder: only the current stage and matching objections. */
export const playbookPromptContextSchema = z.object({
  stage: salesStageSchema,
  stageGuidance: z.string(),
  closingStyle: closingStyleSchema,
  objections: z.array(playbookObjectionSchema.pick({ id: true, trigger: true, response: true })).max(2),
});
export type PlaybookPromptContext = z.infer<typeof playbookPromptContextSchema>;

/* ---- Outcome attribution (read-only) ------------------------------------------------------ */

export const aiRunsSummaryQuerySchema = z.object({
  /** Look-back window in days. */
  days: z.coerce.number().int().min(1).max(365).default(30),
});
export type AiRunsSummaryQuery = z.infer<typeof aiRunsSummaryQuerySchema>;

export const playbookSummaryRowSchema = z.object({
  /** Stage key or objection id. */
  key: z.string(),
  runs: z.number().int().nonnegative(),
  /** Distinct conversations among those runs. */
  conversations: z.number().int().nonnegative(),
  /** Conversations that later got a quote accepted. */
  quoteAccepted: z.number().int().nonnegative(),
  /** Conversations that later got an order paid with verified_by webhook | reconciliation | manual. */
  paidVerified: z.number().int().nonnegative(),
});
export type PlaybookSummaryRow = z.infer<typeof playbookSummaryRowSchema>;

export const aiRunsSummarySchema = z.object({
  days: z.number().int(),
  byStage: z.array(playbookSummaryRowSchema),
  byObjection: z.array(playbookSummaryRowSchema),
});
export type AiRunsSummary = z.infer<typeof aiRunsSummarySchema>;
